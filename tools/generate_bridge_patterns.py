"""Generate bounded ABI-family recognizers from reviewed stock fixture DLLs."""
import argparse,pathlib,struct
import inspect_hooks as h

def generate(root,out):
    paths={v:root/'history'/f'ReSkate-{v}.dll' for v in ['1.1.5','1.1.6']}
    paths.update({'1.1.7':root/'ReSkate-1.1.7.dll','1.1.8':root/'release-1.1.8/ReSkate.dll','2.0.0':root/'ReSkate-2.0.0.dll','2.0.1':root/'ReSkate-2.0.1.dll','2.0.2':root/'ReSkate-2.0.2.dll','2.0.3':root/'ReSkate-2.0.3.dll','2.0.4':root/'ReSkate-2.0.4.dll','2.0.5':root/'ReSkate-2.0.5.dll','2.0.6':root/'ReSkate-2.0.6.dll'})
    table=h.profiles(pathlib.Path(__file__).resolve().parents[1]/'src/stock_contract.h')
    patterns=[]
    for version,path in paths.items():
        im=h.Image(path);p=table[im.digest][1]
        getter=h.calls(im.code(p['status_rva'],256))[0]
        ctor=h.unique([i.operands[0].imm for i in im.code(getter,134) if i.mnemonic=='call'
            and i.operands[0].type==h.X86_OP_IMM and any(j.op_str==f'rcx, [rdi + {0x5c0 if version == "2.0.6" else 0x500 if version in ("2.0.3", "2.0.4", "2.0.5") else 0x4e8 if version in ("2.0.0", "2.0.1", "2.0.2") else 0x4e0:#x}]' for j in im.code(i.operands[0].imm,2048))],'constructor')
        mutex=im.code(p['mutex_lock_rva'],7)[1].operands[0].imm
        init=h.source_initializer(im)
        # Trace callback registration immediately before the named StartV3 call.
        start_export=im.export('DingoSDKOverlayStartV3');registration=[]
        for sec in im.pe.sections:
            if not sec.Characteristics&0x20000000:continue
            data=sec.get_data()
            for pos in range(len(data)-5):
                if data[pos]==0xe8 and sec.VirtualAddress+pos+5+struct.unpack_from('<i',data,pos+1)[0]==start_export:
                    registration.append(sec.VirtualAddress+pos)
        call=h.unique(registration,'callback registration')
        start,_=im.function(call);code=im.code(start,call-start+5)
        stack=h.unique([i.operands[1].mem.disp for i in code[-5:] if i.mnemonic=='lea' and i.op_str.startswith('rcx, [rsp')],'callback stack')
        callbacks={}
        for a,b in zip(code,code[1:]):
            if a.mnemonic=='lea' and h.rip(a) and a.op_str.startswith('rax,') and b.mnemonic=='mov' and b.op_str.endswith(', rax'):
                callbacks[b.operands[0].mem.disp]=h.destination(a)
        roles={'status':(p['status_rva'],166),'getter':(getter,134),'mutex':(mutex,96),
            'unlock':(p['mutex_unlock_rva'],34),'fov':(p['write_fov_rva'],103),
            'init':(init,176),'ctor':(ctor,96),'read':(callbacks[stack+8],256),'queue':(callbacks[stack+24],256)}
        for role,(address,size) in roles.items():
            instructions=im.code(address,size)
            size=instructions[-1].address+instructions[-1].size-address
            data=im.pe.get_data(address,size);mask=bytearray([255]*size)
            for i in instructions:
                spans=[]
                if h.rip(i):spans.append((i.disp_offset,i.disp_size))
                if i.mnemonic.startswith('j') or i.mnemonic=='call':spans.append((i.imm_offset,i.imm_size))
                if role=='getter' and i.address-address==0x67 and i.mnemonic=='mov' and i.op_str.startswith('ecx,'):spans.append((i.imm_offset,i.imm_size))
                for offset,length in spans:
                    for n in range(length):mask[i.address-address+offset+n]=0
            boundaries=[i.address-address for i in instructions]+[size]
            patterns.append((role,data,bytes(mask),boundaries))
    lines=['// Generated by tools/generate_bridge_patterns.py. ABI families 1.1.5-1.1.8 and hash-pinned 2.0.0-2.0.6.', '#pragma once',
        'namespace jishsfirstpersonmod::compatibility {',
        'struct Pattern { const char* role; const unsigned char* bytes; const unsigned char* mask; const unsigned short* boundaries; unsigned size,count; };']
    for n,(role,data,mask,bounds) in enumerate(patterns):
        for name,values,typ in [('bytes',data,'unsigned char'),('mask',mask,'unsigned char'),('bounds',bounds,'unsigned short')]:
            lines.append(f'inline constexpr {typ} p{n}_{name}[]={{'+','.join(str(v) for v in values)+'};')
    lines.append('inline constexpr Pattern patterns[]={')
    for n,(role,data,mask,bounds) in enumerate(patterns):lines.append(f'{{"{role}",p{n}_bytes,p{n}_mask,p{n}_bounds,{len(data)},{len(bounds)-1}}},')
    lines+=['};','}'];out.write_text('\n'.join(lines)+'\n')

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--fixtures',type=pathlib.Path,required=True);p.add_argument('--output',type=pathlib.Path,required=True);a=p.parse_args();generate(a.fixtures,a.output)
